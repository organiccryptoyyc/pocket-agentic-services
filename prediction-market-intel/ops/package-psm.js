#!/usr/bin/env node
// Builds the Pocket Service Manager deploy folder for prediction-market-intel:
//   <out>/backend/  Dockerfile, package.json, server.js, lib/
//   <out>/deploy/docker-compose.yaml
// <out> defaults to ~/Downloads/prediction-market-intel (PSM's services root).
// card.json and service.json in <out> belong to PSM and are never touched.
//
// The compose file keeps the live container's identity (image, container name,
// FETCH_TIMEOUT_MS), so a PSM deploy (compose project "prediction-market-intel")
// replaces the container started from the pre-PSM layout in place, and the
// relayer's backend URL http://prediction-market-intel-backend:8080 is unchanged.
"use strict";

const fs = require("fs");
const os = require("os");
const path = require("path");

const SRC = path.join(__dirname, "..");
const OUT = process.argv[2] || path.join(os.homedir(), "Downloads", "prediction-market-intel");

const COMPOSE = `# prediction-market-intel backend (MainNet), in Pocket Service Manager's layout.
# Generated by ops/package-psm.js; don't edit the copy.
#
# PSM: deploy_ship this folder as "prediction-market-intel", then supplier_run deploy
# "prediction-market-intel" (health /v1/health). The main stack already routes
# prediction-market-intel -> http://prediction-market-intel-backend:8080.

services:
  backend:
    build: ../backend
    image: prediction-market-intel-backend:latest
    container_name: prediction-market-intel-backend
    restart: unless-stopped
    environment:
      FETCH_TIMEOUT_MS: "12000"
    expose:
      - "8080"
    networks: [supplier]

networks:
  supplier:
    external: true
    name: pocket-supplier
`;

function copy(rel, dest) {
  const from = path.join(SRC, rel);
  const to = path.join(OUT, dest, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

fs.rmSync(path.join(OUT, "backend"), { recursive: true, force: true });
fs.rmSync(path.join(OUT, "deploy"), { recursive: true, force: true });
for (const rel of ["Dockerfile", "package.json", "server.js", "lib"]) copy(rel, "backend");
fs.mkdirSync(path.join(OUT, "deploy"), { recursive: true });
fs.writeFileSync(path.join(OUT, "deploy", "docker-compose.yaml"), COMPOSE, "utf8");

const version = /const VERSION = "([^"]+)"/.exec(fs.readFileSync(path.join(SRC, "server.js"), "utf8"))[1];
console.log(`packaged prediction-market-intel v${version} -> ${OUT}`);
